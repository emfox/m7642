import os, re
D=os.path.expanduser("~/Debian/m7642/probes/handoff")

# 1) 恢复 .org 0x10
p=os.path.join(D,"tramp-postmmu.S"); s=open(p).read()
if "\t.org\t0x10" not in s:
    s=s.replace("""	.globl	_start_kva
_start_kva:""","""	/* Pinned: the checkpoint patch is "bl Image+0x36c010", so this entry must
	 * stay at blob offset 0x10.  It drifted to 0x8 once when _start grew to two
	 * instructions and every checkpoint then jumped into _start's branch; three
	 * device runs were lost.  build-postmmu.sh asserts this offset. */
	.org	0x10
	.globl	_start_kva
_start_kva:""",1)
    open(p,"w").write(s); print("已恢复 .org 0x10")

# 2) 两个 stale 脚本：改用 tramp-entries.env
for name, old, new in [
 ("mk-postmmu-images.sh", "$((TRAMP_AT + 4))", "$TRAMP_KVA_ENTRY"),
 ("mk-emap-images.sh",    "$((TRAMP_AT + 4))", "$TRAMP_KVA_ENTRY"),
]:
    p=os.path.join(D,name); s=open(p).read()
    if old in s:
        if ". ./tramp-entries.env" not in s:
            s=s.replace("set -eu","set -eu\n. ./tramp-entries.env\t# entry offsets, generated by build-postmmu.sh",1)
        s=s.replace(old,new); open(p,"w").write(s); print(name,"改读 tramp-entries.env")
    else:
        print(name,"未匹配")
