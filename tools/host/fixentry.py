import os
D=os.path.expanduser("~/Debian/m7642/probes/handoff")

# ---- 1. 把 _start_kva 钉在固定偏移 0x10，杜绝"入口漂移" ----
p=os.path.join(D,"tramp-postmmu.S"); s=open(p).read()
old="""	.globl	_start_kva
_start_kva:"""
new="""	/* Pinned: the checkpoint patch is "bl Image+0x36c010", so this entry must
	 * stay at blob offset 0x10.  (It silently drifted to 0x8 once when _start
	 * grew to two instructions, and every checkpoint then jumped into _start's
	 * branch -- skipping the AT probe and running with the wrong x5.  Two runs
	 * were lost to that.  build-postmmu.sh now asserts this offset.) */
	.org	0x10
	.globl	_start_kva
_start_kva:"""
assert old in s and "\t.org\t0x10" not in s
open(p,"w").write(s.replace(old,new,1)); print("tramp: _start_kva 钉在 0x10")

# ---- 2. build-postmmu.sh：断言入口偏移，并写出一份单一来源 ----
p=os.path.join(D,"build-postmmu.sh"); s=open(p).read()
old="""ls -l tramp-postmmu.bin abort-postmmu.bin abort-rung.bin"""
new="""# Entry offsets are load-bearing: the image patchers hard-code them.  Assert
# them here and write the one file they should read instead of guessing.
NMOFF() { aarch64-buildroot-linux-gnu-nm tramp-postmmu.o |
	  awk -v s="$1" '$3 == s { print "0x" $1 }'; }
PA_ENTRY=$(NMOFF _start)
KVA_ENTRY=$(NMOFF _start_kva)
FDT_ENTRY=$(NMOFF _start_fdt)
[ "$PA_ENTRY"  = "0x0"  ] || { echo "FAIL: _start at $PA_ENTRY, expected 0x0" >&2; exit 1; }
[ "$KVA_ENTRY" = "0x10" ] || { echo "FAIL: _start_kva at $KVA_ENTRY, expected 0x10" >&2; exit 1; }
[ "$FDT_ENTRY" = "0xc0" ] || { echo "FAIL: _start_fdt at $FDT_ENTRY, expected 0xc0" >&2; exit 1; }
TRAMP_AT=0x36c000
cat > tramp-entries.env <<EOT
# generated by build-postmmu.sh -- do not edit
TRAMP_AT=$TRAMP_AT
TRAMP_PA_ENTRY=$(( TRAMP_AT + PA_ENTRY ))
TRAMP_KVA_ENTRY=$(( TRAMP_AT + KVA_ENTRY ))
TRAMP_FDT_ENTRY=$(( TRAMP_AT + FDT_ENTRY ))
EOT
echo "entries: PA=$(printf %#x $(( TRAMP_AT + PA_ENTRY ))) KVA=$(printf %#x $(( TRAMP_AT + KVA_ENTRY ))) FDT=$(printf %#x $(( TRAMP_AT + FDT_ENTRY )))"
ls -l tramp-postmmu.bin abort-postmmu.bin abort-rung.bin"""
assert old in s
open(p,"w").write(s.replace(old,new,1)); print("build: 入口断言 + tramp-entries.env")

# ---- 3. mk-zfix.sh / mk-aligned.sh：改读那份文件，不再写死 0x36c004/0x36c000 ----
for name, old_blk, new_blk in [
 ("mk-zfix.sh",
  'kva) TGT=0x36c004 ;;   # tramp\'s kernel-VA entry\npa)  TGT=0x36c000 ;;   # tramp\'s physical entry',
  '. ./tramp-entries.env\nkva) TGT=$TRAMP_KVA_ENTRY ;;   # tramp\'s kernel-VA entry\npa)  TGT=$TRAMP_PA_ENTRY ;;   # tramp\'s physical entry'),
]:
    p=os.path.join(D,name); s=open(p).read()
    if old_blk in s:
        open(p,"w").write(s.replace(old_blk,new_blk,1)); print(name,"改读 tramp-entries.env")
    else: print(name,"未匹配（需人工看）")

p=os.path.join(D,"mk-aligned.sh"); s=open(p).read()
if '--patch "$OFF=0x36c000"' in s:
    s=s.replace('--patch "$OFF=0x36c000"','--patch "$OFF=$TRAMP_PA_ENTRY"')
    s=s.replace('. ./build-postmmu.sh >/dev/null','. ./build-postmmu.sh >/dev/null') 
    open(p,"w").write(s); print("mk-aligned.sh 改用变量")
