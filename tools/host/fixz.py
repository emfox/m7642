import os
D=os.path.expanduser("~/Debian/m7642/probes/handoff")
p=os.path.join(D,"mk-zfix.sh"); s=open(p).read()
# 必须先 build 再 source（因为 env 由 build 生成），并把 source 放到 case 之前
s=s.replace("""case "$ENTRY" in
. ./tramp-entries.env
kva) TGT=$TRAMP_KVA_ENTRY ;;   # tramp's kernel-VA entry
pa)  TGT=$TRAMP_PA_ENTRY ;;   # tramp's physical entry
esac

KADDR=0x20280000 ./build-postmmu.sh >/dev/null""",
"""KADDR=0x20280000 ./build-postmmu.sh >/dev/null
. ./tramp-entries.env		# entry offsets, generated by build-postmmu.sh
case "$ENTRY" in
kva) TGT=$TRAMP_KVA_ENTRY ;;   # tramp's kernel-VA entry
pa)  TGT=$TRAMP_PA_ENTRY ;;   # tramp's physical entry
esac""")
open(p,"w").write(s); print("mk-zfix.sh 顺序修正")

# env 用十六进制更好读
p=os.path.join(D,"build-postmmu.sh"); s=open(p).read()
s=s.replace('TRAMP_PA_ENTRY=$(( TRAMP_AT + PA_ENTRY ))','TRAMP_PA_ENTRY=$(printf %#x $(( TRAMP_AT + PA_ENTRY )))')
s=s.replace('TRAMP_KVA_ENTRY=$(( TRAMP_AT + KVA_ENTRY ))','TRAMP_KVA_ENTRY=$(printf %#x $(( TRAMP_AT + KVA_ENTRY )))')
s=s.replace('TRAMP_FDT_ENTRY=$(( TRAMP_AT + FDT_ENTRY ))','TRAMP_FDT_ENTRY=$(printf %#x $(( TRAMP_AT + FDT_ENTRY )))')
open(p,"w").write(s); print("env 改十六进制")
