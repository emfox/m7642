#!/bin/bash
# Build the post-MMU abort blobs.  Usage: build-postmmu.sh
#
# The tramp hard-codes the physical addresses of boot_args, _stext and _end,
# plus PRIMARY_ENTRY_PA, so they are derived from System.map.  Re-run this
# after every kernel rebuild.
set -eu
cd "$(dirname "$0")"
TC=${TC:-/home/emfox/Debian/m7642-build/toolchain/gcc13/bin}
KERNEL=${KERNEL:-/home/emfox/Debian/m7642-build/kernel/linux-main}
SYSMAP=${SYSMAP:-$KERNEL/System.map}
KADDR=${KADDR:-0x20280000}
export PATH="$TC:$PATH"

# PRIMARY_ENTRY_PA belongs to the FACTORY kernel, which the handover stub always
# copies to 0x20280000 -- it must not follow KADDR (our kernel's load address).
FACTORY_KADDR=${FACTORY_KADDR:-0x20280000}
DEFS=$(python3 - "$SYSMAP" "$KADDR" "$FACTORY_KADDR" <<'PY'
import sys
syms = {}
for line in open(sys.argv[1]):
    p = line.split()
    if len(p) >= 3:
        syms[p[2]] = int(p[0], 16)
text = syms["_text"]
kaddr = int(sys.argv[2], 16)
fkaddr = int(sys.argv[3], 16)
pa = lambda n: kaddr + syms[n] - text
print("-DBOOT_ARGS_PA=%#x -DIMAGE_START_PA=%#x -DIMAGE_END_PA=%#x "
      "-DKIMAGE_OFFSET=%#x -DPRIMARY_ENTRY_PA=%#x" %
      ((pa("boot_args"), pa("_stext"), pa("_end"),
       text - kaddr, fkaddr + syms["primary_entry"] - text)))
PY
)
# SAVE_VA lives in the image; the handover stub runs with the MMU off, so it
# needs the physical address.  PA = VA - KIMAGE_OFFSET.
# SAVE_VA / TABLE_VA are kernel-image VAs and MUST be passed to the
# assembler.  Pull KIMAGE_OFFSET out of DEFS as a clean token: using
# ${DEFS##*-DKIMAGE_OFFSET=} drags the remaining defines along, the
# arithmetic then fails and silently falls back to a stale constant.
KOFF=$(printf '%s\n' $DEFS | sed -n 's/^-DKIMAGE_OFFSET=//p' | head -1)
KOFF=${KOFF:-0xffffffc05fd80000}
SAVE_VA=${SAVE_VA:-0xffffffc08061a000}
TABLE_VA=${TABLE_VA:-0xffffffc080601000}
SAVE_PA=$(python3 -c "print(hex($SAVE_VA - $KOFF))")
TABLE_PA=$(python3 -c "print(hex($TABLE_VA - $KOFF))")
printf 'save %s->%s  table %s->%s  (KOFF=%s)\n' \
       $SAVE_VA $SAVE_PA $TABLE_VA $TABLE_PA $KOFF
SYMDEFS=""
i=0
for spec in ${READOUT_SYMS:-}; do
	SYMDEFS="$SYMDEFS -DSYM${i}_VA=$spec"
	i=$((i+1))
	[ $i -ge 8 ] && break
done
STUB_AT=${STUB_AT:-0x1400000}
HANDOVER_PA=$(python3 -c "print(hex($KADDR + $STUB_AT + 0x200))")
DEFS="$DEFS -DHANDOVER_PA=$HANDOVER_PA -DSTUB_AT=$STUB_AT -DSAVE_PA=$SAVE_PA -DSAVE_VA=$SAVE_VA -DTABLE_PA=$TABLE_PA -DTABLE_VA=$TABLE_VA -DCOUNT_N=${COUNT_N:-1} $SYMDEFS"
echo "defs: $DEFS  WORLD_VA=${WORLD_VA:-0}"
aarch64-buildroot-linux-gnu-gcc $DEFS -DWORLD_VA=${WORLD_VA:-0} -c tramp-postmmu.S -o tramp-postmmu.o
aarch64-buildroot-linux-gnu-gcc -DSAVE_PA=${SAVE_PA:-0x20883000} -c abort-postmmu.S -o abort-postmmu.o
# abort-rung.bin is the plain record+handover stub the fcie build scripts
# patch in for the ctl/paint images; it needs no kernel constants.
aarch64-buildroot-linux-gnu-gcc -c abort-rung.S -o abort-rung.o
for f in tramp-postmmu abort-postmmu abort-rung; do
	aarch64-buildroot-linux-gnu-objcopy -O binary --only-section=.text "$f.o" "$f.bin"
done
# Entry offsets are load-bearing: the image patchers hard-code them.  Assert
# them here and write the one file they should read instead of guessing.
NMOFF() { aarch64-buildroot-linux-gnu-nm tramp-postmmu.o |
	  awk -v s="$1" '$3 == s { print "0x" $1 }'; }
PA_ENTRY=$(NMOFF _start)
KVA_ENTRY=$(NMOFF _start_kva)
FDT_ENTRY=$(NMOFF _start_fdt)
[ $((PA_ENTRY))  -eq 0   ] || { echo "FAIL: _start at $PA_ENTRY, expected 0x0" >&2; exit 1; }
[ $((KVA_ENTRY)) -eq 16  ] || { echo "FAIL: _start_kva at $KVA_ENTRY, expected 0x10" >&2; exit 1; }
[ $((FDT_ENTRY)) -eq 192 ] || { echo "FAIL: _start_fdt at $FDT_ENTRY, expected 0xc0" >&2; exit 1; }
# The blob must live in .text (it has to be executable) but must NOT overlap
# live code: 0x36e000..0x370000 is a genuinely free 8 KB tail, because
# __static_call_text_start == __static_call_text_end == __hyp_text_end == 0x36e000
# (both sections are empty in this config) and _etext is at 0x370000.
# The previous location 0x36c000 clobbered _raw_spin_trylock / _raw_read_lock* /
# queued_spin_lock_slowpath / queued_read_lock_slowpath, which made the FIRST
# page allocation (it takes the zone lock) jump into the blob and hang --
# indistinguishable from a kernel bug until it was audited.
TRAMP_AT=0x36e000
cat > tramp-entries.env <<EOT
# generated by build-postmmu.sh -- do not edit
TRAMP_AT=$TRAMP_AT
TRAMP_PA_ENTRY=$(printf %#x $(( TRAMP_AT + PA_ENTRY )))
TRAMP_KVA_ENTRY=$(printf %#x $(( TRAMP_AT + KVA_ENTRY )))
TRAMP_FDT_ENTRY=$(printf %#x $(( TRAMP_AT + FDT_ENTRY )))
EOT
echo "entries: PA=$(printf %#x $(( TRAMP_AT + PA_ENTRY ))) KVA=$(printf %#x $(( TRAMP_AT + KVA_ENTRY ))) FDT=$(printf %#x $(( TRAMP_AT + FDT_ENTRY )))"
ls -l tramp-postmmu.bin abort-postmmu.bin abort-rung.bin
md5sum tramp-postmmu.bin abort-postmmu.bin abort-rung.bin

# --- post-build check -------------------------------------------------------
# Assemble can silently leave a stale .bin if an earlier step failed, and a
# stale blob means every later measurement is meaningless.  Re-derive the
# SAVE_VA load from the produced binary and compare.
python3 - "$(dirname "$0")/tramp-postmmu.bin" "$SAVE_VA" <<'PY'
import struct, sys
bin_path, save_va = sys.argv[1], int(sys.argv[2], 0)
d = open(bin_path, "rb").read()
# _start_restore starts at blob offset 0x500 with movz/movk/movk/movk SAVE_VA
off = 0x500
words = struct.unpack_from("<4I", d, off)
def imm(w): return (w >> 5) & 0xffff
val = imm(words[0]) | (imm(words[1]) << 16) | (imm(words[2]) << 32) | (imm(words[3]) << 48)
if val != save_va:
    sys.exit("BUILD FAILED: blob encodes SAVE_VA=%#x but expected %#x "
             "(stale tramp-postmmu.bin?)" % (val, save_va))
print("post-build check: SAVE_VA %#x encoded correctly" % val)
PY
