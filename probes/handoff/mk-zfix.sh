#!/bin/bash
# Checkpoints with the 2 MB-alignment correction forced to zero.
#
#   mk-zfix.sh <checkpoint> <tag> [pa|kva] [extra patcher args...]
#
# <checkpoint> is either a NAME from tools/host/ckpt.py (su3, d0, f1, e1, ...) or
# a raw image offset (0x463980).  Names are resolved against the System.map of
# $KERNEL, and the two image patches (the alignment fix and the dcache nop) are
# resolved the same way -- so a kernel upgrade is just a different $KERNEL, no
# hand-edited offsets anywhere.
set -eu
cd "$(dirname "$0")"
KERNEL=${KERNEL:-$HOME/Debian/m7642-build/kernel/linux-735-out}
OUT=${OUT:-$HOME/Debian/m7642-build/out}
SYSMAP=$KERNEL/System.map
IMAGE=$KERNEL/arch/arm64/boot/Image
WORLD=${WORLD_VA:-0}
IMAGE_OVERRIDE=${IMAGE_OVERRIDE:-}

CKPT=$1; TAG=$2; ENTRY=${3:-kva}; shift 3 2>/dev/null || true

resolve() { python3 ../../tools/host/ckpt.py --sysmap "$SYSMAP" --env "$1" | cut -d= -f2; }

case "$CKPT" in
0x*) OFF=$CKPT ;;
*)   OFF=$(resolve "$CKPT") ;;
esac
ZFIX_ALIGN=$(resolve zfix_align)
ZFIX_NOP=$(resolve zfix_nop)
echo "checkpoint $CKPT -> $OFF   (align patch $ZFIX_ALIGN, nop $ZFIX_NOP)"

KADDR=0x20280000 KERNEL="$KERNEL" WORLD_VA="$WORLD" ./build-postmmu.sh >/dev/null
. ./tramp-entries.env		# entry offsets, generated by build-postmmu.sh
case "$ENTRY" in
kva) TGT=$TRAMP_KVA_ENTRY ;;   # tramp's kernel-VA entry
pa)  TGT=$TRAMP_PA_ENTRY ;;   # tramp's physical entry
esac

python3 ../../tools/host/mk-mainline-abort.py \
	--image "$IMAGE" \
	--word "$ZFIX_ALIGN=0xaa1f03f9" \
	--patch "0x4=0x36c0c0" --patch "$OFF=$TGT" \
	--stub abort-postmmu.bin --tramp tramp-postmmu.bin --tramp-at 0x36c000 \
	--nop "$ZFIX_NOP" \
	--out "$OUT/m7642-$TAG.img"
